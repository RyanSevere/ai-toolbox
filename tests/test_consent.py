class NoConsole(unittest.TestCase):
    """End to end: piped input and no console, as an agent's shell would run it."""

    def test_piped_input_with_no_console_refuses_and_writes_nothing(self):
        """Intent: the consent command refuses piped input. A `yes` on
        stdin is exactly what a script would send, so it must not count."""
        folder = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, folder, ignore_errors=True)
        (folder / "profile.yaml").write_text(PROFILE, encoding="utf-8", newline="\n")
        gates = folder / "seeds" / "githooks" / "gates"
        gates.mkdir(parents=True)
        (gates / "alpha.sh").write_text("#!/bin/sh\n", encoding="utf-8", newline="\n")
        kwargs = ({"creationflags": 0x00000008} if os.name == "nt"  # DETACHED_PROCESS
                  else {"start_new_session": True})
        result = subprocess.run(
            [sys.executable, str(ROOT / "consent.py"), "--profile", str(folder), "--init"],
            input="yes\n", capture_output=True, text=True, timeout=60, **kwargs)
        self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("no interactive console", (result.stdout + result.stderr).lower())
        self.assertFalse((folder / consent.LOCK_NAME).exists())
        self.assertEqual((folder / "profile.yaml").read_text(encoding="utf-8"), PROFILE)


