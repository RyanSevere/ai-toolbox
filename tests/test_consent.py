import consent  # noqa: E402
import yaml  # noqa: E402

PROFILE = """# A comment the consent command must leave alone.
source:
  repo: example
  key: ex
"""


class ProfileCase(unittest.TestCase):
    """A throwaway profile directory with its own seeded gates."""

    gates = ("alpha", "beta")

    def setUp(self):
        self.dir = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.dir, ignore_errors=True)
        (self.dir / "profile.yaml").write_text(PROFILE, encoding="utf-8", newline="\n")
        self.known = list(self.gates)

    def profile_text(self) -> str:
        return (self.dir / "profile.yaml").read_text(encoding="utf-8")

    def features(self) -> dict | None:
        return yaml.safe_load(self.profile_text()).get("features")

    def lock_path(self) -> Path:
        return self.dir / consent.LOCK_NAME

    def answer(self, reply: str | None):
        """Patch the console with one that answers `reply`, or never answers if None."""
        if reply is None:
            never = threading.Event()

            class Silent:
                def readline(self):
                    never.wait()
                    return ""

            console = Silent()
        else:
            console = io.StringIO(reply + "\n")
        return mock.patch.object(consent, "open_console", return_value=console)

    def run_main(self, *args: str) -> int:
        with mock.patch.object(consent, "known_gates", return_value=self.known), \
                mock.patch("sys.stderr", new_callable=io.StringIO) as err, \
                mock.patch("sys.stdout", new_callable=io.StringIO) as out:
            code = consent.main(["--profile", str(self.dir), *args])
        self.output = out.getvalue() + err.getvalue()
        return code


class LockFormat(ProfileCase):
    """The lock is generated, says so, and pins the features: it was written from."""

    def test_the_lock_says_it_is_generated_and_not_to_be_edited(self):
        """Intent: a "generated by the consent command - do not edit" header."""
        text = consent.render_lock({"gates": {"alpha": True, "beta": False}})
        self.assertIn("generated by consent.py", text.lower())
        self.assertIn("do not edit", text.lower())

    def test_the_lock_round_trips(self):
        """Intent: the lock holds the flags and the hash of features:."""
        features = {"gates": {"alpha": True, "beta": False}}
        lock = consent.parse_lock(consent.render_lock(features), "profile.lock")
        self.assertEqual(lock["gates"], {"alpha": True, "beta": False})
        self.assertEqual(lock["hash"], consent.features_hash(features))

    def test_the_hash_ignores_key_order(self):
        """Intent: the hash is of the canonical features: section, so a
        reordered profile.yaml is not a change."""
        self.assertEqual(consent.features_hash({"gates": {"alpha": True, "beta": False}}),
                         consent.features_hash({"gates": {"beta": False, "alpha": True}}))

    def test_a_malformed_lock_refuses(self):
        """Intent: unknown is not zero - a lock that cannot be read is not an empty lock."""
        for text in ("hash=abc\n", "gate.alpha=maybe\n", "nonsense\n", ""):
            with self.subTest(text=text), self.assertRaises(consent.ConsentError):
                consent.parse_lock(text, "profile.lock")


class Check(ProfileCase):
    """What sync.py and the runner call: refuse any disagreement, naming each flag."""

    def lock(self, gates: dict) -> None:
        self.lock_path().write_text(consent.render_lock({"gates": gates}), encoding="utf-8")

    def test_matching_lock_and_features_pass(self):
        """Intent: only a mismatch fails the render."""
        self.lock({"alpha": True, "beta": True})
        consent.check(self.dir, {"gates": {"alpha": True, "beta": True}}, self.known)

    def test_a_hand_edited_flag_is_refused_by_name(self):
        """Intent: a features: edit without the consent command fails,
        naming the flag."""
        self.lock({"alpha": True, "beta": True})
        with self.assertRaises(consent.ConsentError) as caught:
            consent.check(self.dir, {"gates": {"alpha": True, "beta": False}}, self.known)
        self.assertIn("beta", str(caught.exception))
        self.assertNotIn("alpha", str(caught.exception))

    def test_a_hand_edited_lock_is_refused(self):
        """Intent: only the consent command writes the lock. A flag changed
        in the lock without its hash leaves the hash describing other flags."""
        self.lock({"alpha": True, "beta": True})
        text = self.lock_path().read_text(encoding="utf-8").replace("gate.beta=on", "gate.beta=off")
        self.lock_path().write_text(text, encoding="utf-8")
        with self.assertRaises(consent.ConsentError):
            consent.check(self.dir, {"gates": {"alpha": True, "beta": False}}, self.known)

    def test_no_lock_refuses_and_says_how_to_make_one(self):
        """Intent: no lock refuses and points at the one-time
        consent run, rather than treating every gate as enabled."""
        with self.assertRaises(consent.ConsentError) as caught:
            consent.check(self.dir, None, self.known)
        self.assertIn("core/consent.py --profile . --init", str(caught.exception))

    def test_a_gate_with_no_flag_is_refused(self):
        """Intent: a gate added to the core after the lock was written has not been consented
        to either way, so it is named rather than silently run or skipped."""
        self.lock({"alpha": True})
        with self.assertRaises(consent.ConsentError) as caught:
            consent.check(self.dir, {"gates": {"alpha": True}}, self.known)
        self.assertIn("beta", str(caught.exception))

    def test_a_flag_for_no_gate_is_refused(self):
        """Intent: a misspelled flag must not read as a gate switched off."""
        with self.assertRaises(consent.ConsentError) as caught:
            consent.validate_features({"gates": {"alpha": True, "beta": True, "gamma": False}},
                                      self.known)
        self.assertIn("gamma", str(caught.exception))

    def test_a_flag_that_is_not_a_boolean_is_refused(self):
        """Intent: `off` as a string is truthy; a flag is true or false, nothing else."""
        with self.assertRaises(consent.ConsentError):
            consent.validate_features({"gates": {"alpha": "off", "beta": True}}, self.known)


class Command(ProfileCase):
    """The consent command: states each change, applies only on an explicit yes."""

    def test_init_with_no_features_enables_every_gate_on_yes(self):
        """Intent: the one-time setup run writes features: and
        the lock together, every known gate on."""
        with self.answer("yes"):
            self.assertEqual(self.run_main("--init"), 0, self.output)
        self.assertEqual(self.features(), {"gates": {"alpha": True, "beta": True}})
        consent.check(self.dir, self.features(), self.known)

    def test_set_changes_one_flag_and_states_its_consequence(self):
        """Intent: states each change and its consequence, applies on yes."""
        with self.answer("yes"):
            self.run_main("--init")
        with self.answer("yes"):
            self.assertEqual(self.run_main("--set", "beta=off"), 0, self.output)
        self.assertIn("beta: on -> off", self.output)
        self.assertIn("no longer run", self.output)
        self.assertEqual(self.features(), {"gates": {"alpha": True, "beta": False}})
        consent.check(self.dir, self.features(), self.known)

    def test_the_rest_of_profile_yaml_is_left_alone(self):
        """Intent: the consent command owns features:, not the file - comments elsewhere in
        profile.yaml survive it."""
        with self.answer("yes"):
            self.run_main("--init")
        self.assertTrue(self.profile_text().startswith(PROFILE))

    def test_an_empty_features_section_is_replaced_not_duplicated(self):
        """Intent: the example profile ships `features: {}`; init must replace that line, not
        append a second features: key that YAML would silently let win."""
        (self.dir / "profile.yaml").write_text(PROFILE + "features: {}\n\ntargets: {}\n",
                                               encoding="utf-8", newline="\n")
        with self.answer("yes"):
            self.assertEqual(self.run_main("--init"), 0, self.output)
        self.assertEqual(self.profile_text().count("features:"), 1)
        self.assertIn("\n\ntargets: {}\n", self.profile_text())
        self.assertEqual(self.features(), {"gates": {"alpha": True, "beta": True}})

    def test_anything_but_an_explicit_yes_refuses(self):
        """Intent: "explicit informed concent". `y` is not explicit."""
        for reply in ("y", "", "no", "YES please"):
            with self.subTest(reply=reply), self.answer(reply):
                self.assertNotEqual(self.run_main("--init"), 0)
                self.assertFalse(self.lock_path().exists())
                self.assertEqual(self.profile_text(), PROFILE)

    def test_silence_times_out_to_a_refusal(self):
        """Intent: the prompt times out after 2 minutes of inactivity, and a timeout fails."""
        with self.answer(None), mock.patch.object(consent, "TIMEOUT_SECONDS", 0.2):
            self.assertNotEqual(self.run_main("--init"), 0)
        self.assertIn("timed out", self.output.lower())
        self.assertFalse(self.lock_path().exists())
        self.assertEqual(self.profile_text(), PROFILE)

    def test_the_timeout_is_two_minutes(self):
        """Intent: "2 minutes of inactivity"."""
        self.assertEqual(consent.TIMEOUT_SECONDS, 120)

    def test_init_refuses_when_a_lock_exists(self):
        """Intent: init is setup; once a lock exists, a change is a --set the prompt states."""
        with self.answer("yes"):
            self.run_main("--init")
        with self.answer("yes"):
            self.assertNotEqual(self.run_main("--init"), 0)
        self.assertIn("--set", self.output)

    def test_set_of_an_unknown_gate_refuses_before_asking(self):
        """Intent: a misspelled gate must not be consented to."""
        with self.answer("yes"):
            self.run_main("--init")
        with self.answer("yes") as console:
            self.assertNotEqual(self.run_main("--set", "gamma=off"), 0)
        console.assert_not_called()
        self.assertIn("gamma", self.output)

    def test_set_with_no_change_refuses(self):
        """Characterisation: asking consent for nothing is noise; say so and exit non-zero."""
        with self.answer("yes"):
            self.run_main("--init")
        with self.answer("yes"):
            self.assertNotEqual(self.run_main("--set", "alpha=on"), 0)


