from __future__ import annotations

import argparse
import hashlib
import json
import logging
import os
import re
import sys
import threading
from pathlib import Path
from typing import TextIO

import yaml

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parent
PROFILE_NAME = "profile.yaml"
LOCK_NAME = "profile.lock"
# The prompt times out after 2 minutes of inactivity, and a timeout fails.
TIMEOUT_SECONDS = 120
GATE_NAME = re.compile(r"[a-z0-9][a-z0-9-]*")
HASH = re.compile(r"[0-9a-f]{64}")
LOCK_HEADER = (
    "# Generated by consent.py - do not edit. Only the consent command writes this file,\n"
    "# and sync.py and the pre-push hook refuse when it disagrees with profile.yaml.\n"
    "# Change a gate with: python core/consent.py --profile . --set <gate>=on|off\n"
)
# The block consent.py owns in profile.yaml. Everything outside it is left as written.
FEATURES_COMMENT = "# Gate flags. Written by consent.py with profile.lock - do not edit by hand.\n"


class ConsentError(Exception):
    """A flag change refused, or a lock that disagrees with what it should pin."""


def known_gates(profile_dir: Path) -> list[str]:
    """Every gate the render would ship: the core's, plus the profile's seeded ones."""
    profile_seeds = Path(profile_dir) / "seeds"
    folders = (ROOT / "githooks" / "gates", profile_seeds / "githooks" / "gates")
    return sorted({p.stem for folder in folders if folder.exists() for p in folder.glob("*.sh")})


def validate_features(features: object, known: list[str]) -> dict[str, bool]:
    """The gates map from a features: section, or ConsentError naming what is wrong.

    Every known gate needs a flag and every flag needs a gate, so neither a gate added
    later nor a misspelled flag can be read as a decision nobody made.
    """
    if not isinstance(features, dict) or set(features) != {"gates"}:
        raise ConsentError("features: must hold exactly one key, gates:")
    gates = features["gates"]
    if not isinstance(gates, dict):
        raise ConsentError("features: gates: must map each gate to true or false")
    problems = []
    for name, value in sorted(gates.items(), key=lambda item: str(item[0])):
        if not isinstance(name, str):
            problems.append(f"{name!r}: not a gate name. YAML reads on, off, yes and no as "
                            "true or false unless quoted")
        elif name not in known:
            problems.append(f"{name}: no such gate")
        elif not isinstance(value, bool):
            problems.append(f"{name}: {value!r} is not true or false")
    problems += [f"{name}: no flag" for name in known if name not in gates]
    if problems:
        raise ConsentError("features: gates: " + "; ".join(problems))
    return dict(gates)


def canonical(features: dict) -> str:
    """One spelling of a features: section, so reordering or reformatting is not a change."""
    return json.dumps(features, sort_keys=True, separators=(",", ":"))


def features_hash(features: dict) -> str:
    """The SHA-256 of the canonical features: section."""
    return hashlib.sha256(canonical(features).encode("utf-8")).hexdigest()


def render_lock(features: dict) -> str:
    """The lock text for a features: section: header, hash, one flag per line."""
    lines = [f"hash={features_hash(features)}"]
    lines += [f"gate.{name}={'on' if on else 'off'}"
              for name, on in sorted(features["gates"].items())]
    return LOCK_HEADER + "\n".join(lines) + "\n"


def parse_lock(text: str, where: str) -> dict:
    """{"hash": ..., "gates": {...}} from lock text. Anything unrecognised refuses."""
    digest = None
    gates: dict[str, bool] = {}
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if key == "hash" and sep and HASH.fullmatch(value):
            digest = value
        elif (key.startswith("gate.") and sep and GATE_NAME.fullmatch(key[5:])
              and value in ("on", "off")):
            gates[key[5:]] = value == "on"
        else:
            raise ConsentError(f"{where}:{number}: unrecognised line; the lock is generated "
                               "by consent.py and is never edited by hand")
    if digest is None or not gates:
        raise ConsentError(f"{where} has no hash or no flags, so it pins nothing")
    return {"hash": digest, "gates": gates}


def read_lock(profile_dir: Path) -> dict | None:
    """The parsed lock, or None if there is none."""
    path = Path(profile_dir) / LOCK_NAME
    if not path.exists():
        return None
    return parse_lock(path.read_text(encoding="utf-8"), str(path))


def check(profile_dir: Path, features: object, known: list[str]) -> dict[str, bool]:
    """The consented gate flags, or ConsentError naming each flag that disagrees.

    Called by sync.py before rendering and by the pre-push hook. Never writes: a
    mismatch is resolved by the consent command or by reverting the edit, not here.
    """
    lock = read_lock(profile_dir)
    # Nothing ships a gate, so there is no flag to consent to; once one exists, so must the lock.
    if lock is None and not known and not features:
        return {}
    if lock is None:
        raise ConsentError(f"no {LOCK_NAME} in {profile_dir}. Gate flags are set once at "
                           "setup: run `python core/consent.py --profile . --init` at an "
                           "interactive console")
    if not features:
        raise ConsentError(f"{PROFILE_NAME} has no features: section, but {LOCK_NAME} "
                           "exists. Restore features: or run the consent command")
    gates = validate_features(features, known)
    differing = sorted(name for name in set(gates) | set(lock["gates"])
                       if gates.get(name) != lock["gates"].get(name))
    if differing:
        raise ConsentError(
            f"{PROFILE_NAME} features: and {LOCK_NAME} disagree on: {', '.join(differing)}. "
            "Revert the edit, or change the flag with `python core/consent.py --profile . --set`")
    if features_hash({"gates": gates}) != lock["hash"]:
        raise ConsentError(f"{LOCK_NAME} has been edited by hand: its hash does not match "
                           "its own flags. Restore it from git")
    return gates


def render_features_block(gates: dict[str, bool]) -> str:
    """The features: block consent.py writes into profile.yaml."""
    lines = [FEATURES_COMMENT, "features:\n", "  gates:\n"]
    # Dumped, not formatted: a gate named off or yes must be quoted, or YAML reads a boolean.
    lines += [f"    {yaml.safe_dump({name: on}).strip()}\n" for name, on in sorted(gates.items())]
    return "".join(lines)


def replace_features_block(text: str, block: str) -> str:
    """profile.yaml text with its features: block replaced, or the block appended.

    The block runs from consent.py's own comment line, or the `features:` line, to the
    next line that is neither indented nor blank.
    """
    lines = text.splitlines(keepends=True)
    start = next((i for i, line in enumerate(lines) if re.match(r"features:(\s|$)", line)),
                 None)
    if start is None:
        return text.rstrip("\n") + "\n\n" + block
    end = scan = start + 1
    if start > 0 and lines[start - 1] == FEATURES_COMMENT:
        start -= 1
    while scan < len(lines) and (lines[scan].startswith(" ") or not lines[scan].strip()):
        scan += 1
        if lines[scan - 1].startswith(" "):
            end = scan
    return "".join(lines[:start]) + block + "".join(lines[end:])


def open_console() -> TextIO:
    """The interactive console itself, never stdin. No console means no consent."""
    path = "CONIN$" if os.name == "nt" else "/dev/tty"
    try:
        return open(path, encoding="utf-8")
    except OSError as error:
        raise ConsentError(f"no interactive console ({path}: {error.strerror}). A flag "
                           "changes only by a person typing at a terminal; piped or "
                           "scripted input is refused") from error


def ask(console: TextIO, timeout: float) -> bool:
    """True only if the console answers exactly `yes` within `timeout` seconds."""
    answer: list[str] = []
    reader = threading.Thread(target=lambda: answer.append(console.readline()), daemon=True)
    reader.start()
    reader.join(timeout)
    if reader.is_alive():
        raise ConsentError(f"timed out after {timeout:g} seconds with no answer. Nothing "
                           "was changed")
    return bool(answer) and answer[0].strip() == "yes"


def describe(name: str, before: bool | None, after: bool) -> str:
    """One change and what it does, in the words the prompt shows."""
    state = {True: "on", False: "off", None: "unset"}
    if after:
        consequence = f"pushes run {name}, and CI requires it to pass"
    else:
        consequence = (f"pushes no longer run {name}, and CI no longer requires it. "
                       "Every push names it as skipped")
    return f"  {name}: {state[before]} -> {state[after]}. {consequence}."


def parse_sets(values: list[str], known: list[str]) -> dict[str, bool]:
    """--set NAME=on|off arguments, refused whole if any is malformed or unknown."""
    changes: dict[str, bool] = {}
    for value in values:
        name, sep, state = value.partition("=")
        if not sep or state not in ("on", "off"):
            raise ConsentError(f"--set {value!r}: expected <gate>=on or <gate>=off")
        if name not in known:
            raise ConsentError(f"--set {value!r}: no such gate. Known: {', '.join(known)}")
        changes[name] = state == "on"
    return changes


def write_atomically(path: Path, text: str) -> None:
    """Write in one step, so a reader never sees half a file."""
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    os.replace(tmp, path)


def plan(profile_dir: Path, args: argparse.Namespace, known: list[str]) -> tuple[dict, dict]:
    """(before, after) gate maps for the requested change, refused before any prompt."""
    lock = read_lock(profile_dir)
    data = yaml.safe_load((profile_dir / PROFILE_NAME).read_text(encoding="utf-8")) or {}
    if args.init:
        if lock is not None:
            raise ConsentError(f"{LOCK_NAME} already exists. Change a flag with --set")
        declared = data.get("features")
        after = (validate_features(declared, known) if declared
                 else {name: True for name in known})
        return {}, after
    if lock is None:
        raise ConsentError(f"no {LOCK_NAME} yet. Run `python core/consent.py --profile . --init` first")
    before = dict(lock["gates"])
    after = {**{name: before.get(name, True) for name in known}, **parse_sets(args.set, known)}
    if after == before:
        raise ConsentError("nothing would change; no consent asked for")
    return before, after


def main(argv: list[str] | None = None) -> int:
    """Run the consent command. Non-zero on any refusal, timeout or non-yes."""
    parser = argparse.ArgumentParser(
        prog="consent.py", description="Change gate flags, with explicit consent.")
    parser.add_argument("--profile", type=Path, default=ROOT,
                        help="directory holding profile.yaml (default: this script's own)")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--init", action="store_true",
                      help="first setup: lock features: as declared, or every gate on")
    mode.add_argument("--set", action="append", metavar="GATE=on|off",
                      help="change one gate; repeatable")
    mode.add_argument("--check", action="store_true",
                      help="read-only: refuse if features: and the lock disagree")
    args = parser.parse_args(argv)
    profile_dir = args.profile.resolve()
    try:
        if not (profile_dir / PROFILE_NAME).is_file():
            raise ConsentError(f"no {PROFILE_NAME} in {profile_dir}")
        known = known_gates(profile_dir)
        if not known:
            raise ConsentError("no gates found to flag")
        if args.check:
            data = yaml.safe_load((profile_dir / PROFILE_NAME).read_text(encoding="utf-8"))
            gates = check(profile_dir, (data or {}).get("features"), known)
            print(f"consent: {len(gates)} gate flag(s) match {LOCK_NAME}")
            return 0
        before, after = plan(profile_dir, args, known)
        changes = [describe(name, before.get(name), on) for name, on in sorted(after.items())
                   if before.get(name) != on]
        console = open_console()
        print(f"Gate flag changes for {profile_dir / PROFILE_NAME}:")
        print("\n".join(changes))
        print(f"Type yes to apply. Anything else, or {TIMEOUT_SECONDS:g} seconds of silence, "
              "refuses.")
        sys.stdout.flush()
        if not ask(console, TIMEOUT_SECONDS):
            raise ConsentError("not confirmed with an explicit yes. Nothing was changed")
        profile = profile_dir / PROFILE_NAME
        features = {"gates": after}
        write_atomically(profile, replace_features_block(
            profile.read_text(encoding="utf-8"), render_features_block(after)))
        write_atomically(profile_dir / LOCK_NAME, render_lock(features))
        check(profile_dir, yaml.safe_load(profile.read_text(encoding="utf-8")).get("features"),
              known)
    except ConsentError as error:
        print(f"REFUSED: {error}", file=sys.stderr)
        return 1
    print(f"Written: {PROFILE_NAME} features: and {LOCK_NAME}. Commit both together.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
